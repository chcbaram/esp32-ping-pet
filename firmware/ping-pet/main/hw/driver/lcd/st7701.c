bool st7701InitRegs(esp_lcd_panel_io_handle_t io)
{
  for (int i=0; i<sizeof(init_cmds)/sizeof(init_cmds[0]); i++)
  {
    const st7701_cmd_t *p_cmd = &init_cmds[i];

    if (esp_lcd_panel_io_tx_param(io, p_cmd->cmd, p_cmd->data, p_cmd->len) != ESP_OK)
    {
      logPrintf("[E_] st7701 cmd 0x%02X\n", p_cmd->cmd);
      return false;
    }
    if (p_cmd->delay_ms > 0)
    {
      delay(p_cmd->delay_ms);
    }
  }
  return true;
}

bool st7701DisplayOn(esp_lcd_panel_io_handle_t io, bool on)
{
  return esp_lcd_panel_io_tx_param(io, on ? 0x29 : 0x28, NULL, 0) == ESP_OK;
}

